import { readFile, writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';
import { catalog, disciplineCounts } from '../backend/catalog.js';
import { disciplines } from '../backend/disciplines.js';
const settings = await resolveConfig('.');
const counts = `<!-- catalog-summary:start -->\n**${catalog.length} working labs across ${Object.keys(disciplines).length} disciplines.**\n<!-- catalog-summary:end -->`;
const readme = await readFile('README.md', 'utf8');
const documents = {
  'README.md': readme.replace(
    /<!-- catalog-summary:start -->[\s\S]*?<!-- catalog-summary:end -->/,
    counts,
  ),
  'docs/CATALOG.md': `# Executable lab catalog\n\nGenerated by \`npm run docs:generate\` from \`backend/catalog.js\`. Do not edit this inventory by hand. Historical release guides retain their release-time counts.\n\n${catalog.length} labs; ${Object.keys(disciplines).length} disciplines. Shared labs count once in the total.\n\n| Discipline | Labs |\n| --- | --- |\n${Object.entries(
    disciplines,
  )
    .map(([id, label]) => `| ${label} | ${disciplineCounts[id]} |`)
    .join(
      '\n',
    )}\n\n| Lab | Section | Route | API |\n| --- | --- | --- | --- |\n${catalog.map((lab) => `| ${lab.title} | ${lab.groups.map((id) => disciplines[id]).join(' + ')} | [Open](https://soumadip-nexora.vercel.app${lab.href}) | \`${lab.endpoint}\` |`).join('\n')}\n`,
};
for (const [path, source] of Object.entries(documents)) {
  const expected = await format(source, { ...settings, parser: 'markdown' });
  if (process.argv.includes('--check')) {
    const actual = await readFile(path, 'utf8').catch(() => '');
    if (actual.replaceAll('\r\n', '\n') !== expected) {
      console.error(`${path} is stale; run npm run docs:generate.`);
      process.exitCode = 1;
    }
  } else await writeFile(path, expected);
}
